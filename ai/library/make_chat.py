"""Builds ai/library/chat.json: Edith's chat bank (no live model: every line she can say is here or in
the other library files, pre-rendered in the voice cache).

    python ai/library/make_chat.py          # writes chat.json next to this file

Entry = (id, example phrasings, replies, order). The phrasings are matched loosely (library.chat:
character similarity + word overlap), so a few varied ones per entry cover most ways of asking.
Replies: {name} = what she calls you, {me} = her name, {time} / {date}. Her rules: short, spoken,
no emoji or symbols, never the word "coming", never swears; bossy, sarcastic, teasing, a bit mean.
Orders: follow, come, stay, home, spin, flip front, flip back, flip left, throw, push.
To add lines: add entries to a part file (chat_*.py next to this one) and run this again.
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load_parts() -> list[tuple]:
    entries = []
    for f in sorted(HERE.glob("chat_*.py")):
        spec = importlib.util.spec_from_file_location(f.stem, f)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        entries += m.ENTRIES
    return entries


def check(entries: list[tuple]) -> list[str]:
    problems, seen = [], set()
    for e in entries:
        cid, qs, replies = e[0], e[1], e[2]
        if cid in seen:
            problems.append(f"duplicate id {cid}")
        seen.add(cid)
        for r in replies:
            if re.search(r"\bcoming\b", r, re.I):
                problems.append(f"{cid}: 'coming' in {r!r}")
            if re.search(r"snow ?ball", r, re.I):                     # she throws balls (user, 2026-10-18)
                problems.append(f"{cid}: 'snowball' in {r!r}")
            if "{name}" in r:                                          # she never says names
                problems.append(f"{cid}: {{name}} in {r!r}")
            if any(not (ch.isascii()) for ch in r):
                problems.append(f"{cid}: non-ASCII in {r!r}")
        if len(qs) < 2 or len(replies) < 2:
            problems.append(f"{cid}: needs 2+ phrasings and 2+ replies")
    return problems


def main() -> int:
    entries = load_parts()
    bad = check(entries)
    for b in bad:
        print("!", b)
    out = {"_about": "Edith's chat bank, generated by make_chat.py from chat_*.py (edit those, not this). "
                     "q = example phrasings (matched loosely), a = replies, do = an order to carry out.",
           "entries": [{"id": e[0], "q": e[1], "a": e[2], **({"do": e[3]} if len(e) > 3 and e[3] else {})}
                       for e in entries]}
    (HERE / "chat.json").write_text(json.dumps(out, indent=1, ensure_ascii=True), encoding="utf-8")
    print(f"chat.json: {len(entries)} entries, {sum(len(e[1]) for e in entries)} phrasings, "
          f"{sum(len(e[2]) for e in entries)} replies")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
